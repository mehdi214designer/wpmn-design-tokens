let css = `/**
 * WPMN Design System — Brand Primitive Tokens
 * Auto-generated by scripts/generate-brand-tokens.mjs
 * Do not edit manually — re-run the script to update.
 *
 * HOW IT WORKS
 * ─────────────────────────────────────────────────────────────
 * Apply data-brand="<key>" to <html>, <body>, or any container.
 * The attribute selector overrides --primitive-primary-* (and
 * optionally --primitive-accent-*) for that subtree.
 * All semantic tokens (tokens.css) reference those primitives,
 * so buttons, badges, inputs etc. automatically adopt the brand.
 *
 * WPManageNinja is the default palette (defined in primitives.css).
 * The 14 other brands are listed below.
 *
 * Supported brands:
 *   ${brands.map(b => b[0]).join('\n *   ')}
 *
 * USAGE
 * ─────────────────────────────────────────────────────────────
 * // Full-page brand switch
 * document.documentElement.setAttribute('data-brand', 'fluentforms');
 *
 * // Scoped brand section in JSX
 * <section data-brand="fluentsupport"> … </section>
 */\n\n`;

for (const [key, label, primaryHex, accentHex] of brands) {
  const primaryScale = generateScale(primaryHex);
  const accentScale  = accentHex ? generateScale(accentHex) : null;

  css += `/* ============================================================\n`;
  css += `   ${label}  (primary: ${primaryHex}${accentHex ? `, accent: ${accentHex}` : ''})\n`;
  css += `   ============================================================ */\n`;
  css += `[data-brand="${key}"] {\n`;

  for (const [step, hex] of Object.entries(primaryScale)) {
    css += `  --primitive-primary-${step}: ${hex};\n`;
  }

  if (accentScale) {
    css += `\n  /* Accent (secondary brand colour) */\n`;
    for (const [step, hex] of Object.entries(accentScale)) {
      css += `  --primitive-accent-${step}: ${hex};\n`;
    }
  }

  css += `}\n\n`;
}

