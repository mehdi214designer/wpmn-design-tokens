/**
 * WPMN Brand Primitive Token Generator
 * Generates brand-primitives.css with [data-brand="…"] overrides.
 *
 * WPManageNinja is intentionally excluded — it is the system default
 * already defined in primitives.css. All other brands override the
 * --primitive-primary-* (and optionally --primitive-accent-*) variables.
 */

function hexToHsl(hex) {
  let r = parseInt(hex.slice(1, 3), 16) / 255;
  let g = parseInt(hex.slice(3, 5), 16) / 255;
  let b = parseInt(hex.slice(5, 7), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h, s, l = (max + min) / 2;
  if (max === min) { h = s = 0; }
  else {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r: h = ((g - b) / d + (g < b ? 6 : 0)) / 6; break;
      case g: h = ((b - r) / d + 2) / 6; break;
      case b: h = ((r - g) / d + 4) / 6; break;
    }
  }
  return { h: Math.round(h * 360), s: Math.round(s * 100), l: Math.round(l * 100) };
}

function hslToHex(h, s, l) {
  s /= 100; l /= 100;
  const a = s * Math.min(l, 1 - l);
  const f = n => {
    const k = (n + h / 30) % 12;
    const color = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
    return Math.round(255 * color).toString(16).padStart(2, '0');
  };
  return `#${f(0)}${f(8)}${f(4)}`;
}

function generateScale(hex) {
  const { h, s, l } = hexToHsl(hex);
  // Relative lightness steps, clamped to realistic ranges
  const steps = [
    [50,  { lDelta: +46, sFactor: 0.25 }],
    [100, { lDelta: +40, sFactor: 0.40 }],
    [200, { lDelta: +28, sFactor: 0.60 }],
    [300, { lDelta: +16, sFactor: 0.80 }],
    [400, { lDelta: +8,  sFactor: 0.92 }],
    [500, { lDelta: 0,   sFactor: 1.00 }],  // base
    [600, { lDelta: -10, sFactor: 1.05 }],
    [700, { lDelta: -20, sFactor: 1.08 }],
    [800, { lDelta: -30, sFactor: 1.05 }],
    [900, { lDelta: -38, sFactor: 0.95 }],
    [950, { lDelta: -43, sFactor: 0.80 }],
  ];
  const result = {};
  for (const [step, { lDelta, sFactor }] of steps) {
    const sl = Math.min(97, Math.max(2, l + lDelta));
    const ss = Math.min(100, Math.max(5, Math.round(s * sFactor)));
    result[step] = hslToHex(h, ss, sl);
  }
  return result;
}

